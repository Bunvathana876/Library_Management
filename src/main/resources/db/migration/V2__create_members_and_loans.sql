
-- 1. Library members
CREATE TABLE members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE
);

-- 2. Book borrowing records
CREATE TABLE loans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    book_id BIGINT NOT NULL REFERENCES books(id),
    member_id BIGINT NOT NULL REFERENCES members(id),

    borrowed_on DATE NOT NULL,
    due_on DATE NOT NULL,
    returned_on DATE,

    CONSTRAINT valid_due_date
        CHECK (due_on >= borrowed_on),

    CONSTRAINT valid_return_date
        CHECK (
            returned_on IS NULL
            OR returned_on >= borrowed_on
        )
);

-- Improve lookup performance
CREATE INDEX idx_loans_member
    ON loans(member_id);

CREATE INDEX idx_loans_book
    ON loans(book_id);

-- Each physical book can only have one active loan
CREATE UNIQUE INDEX one_active_loan_per_book
    ON loans(book_id)
    WHERE returned_on IS NULL;
