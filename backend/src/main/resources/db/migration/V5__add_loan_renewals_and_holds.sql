ALTER TABLE loans
    ADD COLUMN renewal_count INTEGER NOT NULL DEFAULT 0
        CHECK (renewal_count >= 0 AND renewal_count <= 2),
    ADD COLUMN last_renewed_on DATE;

CREATE TABLE holds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    book_id BIGINT NOT NULL REFERENCES books(id) ON DELETE CASCADE,
    member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,

    status VARCHAR(24) NOT NULL
        CHECK (status IN ('WAITING', 'READY_FOR_PICKUP', 'FULFILLED', 'CANCELLED', 'EXPIRED')),

    placed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ready_at TIMESTAMP WITH TIME ZONE,
    expires_on DATE,
    fulfilled_at TIMESTAMP WITH TIME ZONE,
    cancelled_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_holds_book_status_placed
    ON holds(book_id, status, placed_at, id);

CREATE INDEX idx_holds_member_status
    ON holds(member_id, status, placed_at);

CREATE UNIQUE INDEX one_active_hold_per_member_book
    ON holds(book_id, member_id)
    WHERE status IN ('WAITING', 'READY_FOR_PICKUP');

CREATE UNIQUE INDEX one_ready_hold_per_book
    ON holds(book_id)
    WHERE status = 'READY_FOR_PICKUP';
