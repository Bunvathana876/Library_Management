ALTER TABLE books
    ADD COLUMN category VARCHAR(80),
    ADD COLUMN shelf_location VARCHAR(60);

CREATE INDEX idx_books_category
    ON books(category);

CREATE TABLE book_copies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    book_id BIGINT NOT NULL REFERENCES books(id) ON DELETE CASCADE,

    barcode VARCHAR(64) NOT NULL UNIQUE,

    status VARCHAR(20) NOT NULL
        CHECK (status IN ('AVAILABLE', 'LOANED', 'ON_HOLD', 'DAMAGED', 'LOST')),

    shelf_location VARCHAR(60),
    condition_notes VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_book_copies_book_status
    ON book_copies(book_id, status);

INSERT INTO book_copies (book_id, barcode, status, shelf_location)
SELECT
    b.id,
    'CPY-' || LPAD(b.id::text, 4, '0') || '-01',
    CASE
        WHEN EXISTS (SELECT 1 FROM loans l WHERE l.book_id = b.id AND l.returned_on IS NULL) THEN 'LOANED'
        WHEN EXISTS (SELECT 1 FROM holds h WHERE h.book_id = b.id AND h.status = 'READY_FOR_PICKUP') THEN 'ON_HOLD'
        WHEN b.available THEN 'AVAILABLE'
        ELSE 'LOANED'
    END,
    b.shelf_location
FROM books b;

ALTER TABLE loans
    ADD COLUMN copy_id BIGINT REFERENCES book_copies(id) ON DELETE SET NULL,
    ADD COLUMN fine_amount NUMERIC(10, 2) NOT NULL DEFAULT 0.00 CHECK (fine_amount >= 0),
    ADD COLUMN fine_status VARCHAR(20) NOT NULL DEFAULT 'NONE'
        CHECK (fine_status IN ('NONE', 'UNPAID', 'PAID', 'WAIVED')),
    ADD COLUMN fine_settled_at TIMESTAMP WITH TIME ZONE,
    ADD COLUMN fine_note VARCHAR(255);

UPDATE loans l
SET copy_id = (
    SELECT bc.id
    FROM book_copies bc
    WHERE bc.book_id = l.book_id
    ORDER BY bc.id ASC
    LIMIT 1
)
WHERE l.copy_id IS NULL;

DROP INDEX IF EXISTS one_active_loan_per_book;

CREATE UNIQUE INDEX one_active_loan_per_copy
    ON loans(copy_id)
    WHERE returned_on IS NULL AND copy_id IS NOT NULL;

CREATE INDEX idx_loans_copy
    ON loans(copy_id);

CREATE INDEX idx_loans_fine_status
    ON loans(fine_status)
    WHERE fine_status = 'UNPAID';

ALTER TABLE holds
    ADD COLUMN copy_id BIGINT REFERENCES book_copies(id) ON DELETE SET NULL;

UPDATE holds h
SET copy_id = (
    SELECT bc.id
    FROM book_copies bc
    WHERE bc.book_id = h.book_id
    ORDER BY bc.id ASC
    LIMIT 1
)
WHERE h.status = 'READY_FOR_PICKUP' AND h.copy_id IS NULL;

DROP INDEX IF EXISTS one_ready_hold_per_book;

CREATE UNIQUE INDEX one_ready_hold_per_copy
    ON holds(copy_id)
    WHERE status = 'READY_FOR_PICKUP' AND copy_id IS NOT NULL;

CREATE INDEX idx_holds_copy
    ON holds(copy_id);

ALTER TABLE members
    ADD COLUMN active BOOLEAN NOT NULL DEFAULT TRUE,
    ADD COLUMN phone VARCHAR(30),
    ADD COLUMN notes VARCHAR(500),
    ADD COLUMN created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP;

CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    recipient_email VARCHAR(254) NOT NULL,

    type VARCHAR(32) NOT NULL
        CHECK (type IN ('HOLD_READY', 'HOLD_EXPIRED', 'DUE_SOON', 'OVERDUE', 'FINE_ASSESSED', 'ACCOUNT')),

    title VARCHAR(160) NOT NULL,
    message VARCHAR(500) NOT NULL,
    reference_key VARCHAR(120),
    read_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_notifications_recipient_created
    ON notifications(recipient_email, created_at DESC);

CREATE UNIQUE INDEX idx_notifications_dedupe
    ON notifications(recipient_email, reference_key)
    WHERE reference_key IS NOT NULL;
